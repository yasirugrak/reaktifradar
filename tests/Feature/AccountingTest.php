<?php
namespace Tests\Feature;
use App\Enerjisa\Models\Account;
use App\Enerjisa\Models\Member;
use Illuminate\Foundation\Testing\RefreshDatabase;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Str;
use Tests\TestCase;
class AccountingTest extends TestCase {
 use RefreshDatabase;
 public function test_accounting_records_payments_quotes_and_isolation(): void {
 \Illuminate\Support\Facades\Http::fake(['*'=>\Illuminate\Support\Facades\Http::response('',503)]);
 $account=Account::create(['name'=>'Test']);
 $member=Member::create(['account_id'=>$account->id,'name'=>'Test','email'=>'accounting@example.test','password'=>'Password12345']);
 $this->get('/muhasebe')->assertRedirect('/panel/login');
 $this->actingAs($member,'enerjisa')->get('/muhasebe')->assertOk();
 $this->postJson('/muhasebe/directory',['kind'=>'person','name'=>'Ada'])->assertCreated();
 $directoryId=DB::table('accounting_directory')->value('id');
 $this->postJson('/muhasebe/directory',['kind'=>'person','name'=>'Ada'])->assertCreated();
 $this->assertDatabaseCount('accounting_directory',1);
 $this->getJson('/muhasebe/directory?kind=person&q=ad')->assertJsonCount(1)->assertJsonFragment(['name'=>'Ada']);
 $this->post('/muhasebe/entries',['token'=>(string)Str::uuid(),'directory_id'=>$directoryId,'type'=>'receivable','currency'=>'TRY','amount'=>'100.25','date'=>'2026-11-08'])->assertSessionHasNoErrors();
 $id=DB::table('accounting_entries')->value('id');
 $payment=['amount'=>'40','date'=>'2026-11-08','token'=>(string)Str::uuid()];
 $this->post("/muhasebe/entries/$id/payments",$payment)->assertSessionHasNoErrors();
 $this->post("/muhasebe/entries/$id/payments",$payment)->assertSessionHasNoErrors();
 $this->assertDatabaseCount('accounting_payments',1);
 $this->postJson('/muhasebe/entries/'.$id.'/amount',['amount'=>'30'])->assertUnprocessable();
 $this->postJson('/muhasebe/entries/'.$id.'/amount',['amount'=>'110'])->assertOk();
 $this->assertDatabaseHas('accounting_entries',['id'=>$id,'amount'=>1100000,'date'=>'2026-11-08']);
 $this->postJson('/muhasebe/entries/'.$id.'/edit',['amount'=>'30','date'=>'2026-11-08'])->assertUnprocessable();
 $this->postJson('/muhasebe/entries/'.$id.'/edit',['amount'=>'120','date'=>'2026-11-09'])->assertUnprocessable();
 $this->postJson('/muhasebe/entries/'.$id.'/edit',['amount'=>'120','date'=>'2026-11-08','note'=>'Düzenlendi'])->assertOk();
 $this->assertDatabaseHas('accounting_entries',['id'=>$id,'amount'=>1200000,'note'=>'Düzenlendi']);
 $this->postJson('/muhasebe/entries/'.$id.'/edit',['amount'=>'100.25','date'=>'2026-11-08'])->assertOk();
 $this->post("/muhasebe/entries/$id/payments",['amount'=>'61','date'=>'2026-11-08','token'=>(string)Str::uuid()])->assertSessionHasErrors('amount');
 $receipt=['directory_id'=>$directoryId,'currency'=>'TRY','amount'=>'70.25','date'=>'2026-11-08','token'=>(string)Str::uuid()];
 $preview=$this->postJson('/muhasebe/tahsilat',$receipt)->assertOk()->assertJsonPath('excess',100000)->json();
 $this->postJson('/muhasebe/tahsilat',$receipt+['confirmation'=>$preview['confirmation']])->assertOk()->assertJsonPath('saved',true);
 $this->postJson('/muhasebe/tahsilat',$receipt+['confirmation'=>$preview['confirmation']])->assertOk();
 $this->assertDatabaseCount('accounting_receipts',1);
 $this->assertDatabaseHas('accounting_entries',['type'=>'debt','amount'=>100000,'directory_id'=>$directoryId]);
 // Undo fixture effects so the existing partial-payment checks retain their scope.
 DB::table('accounting_payments')->where('entry_id',$id)->where('amount',602500)->delete();
 DB::table('accounting_entries')->where('type','debt')->delete();
 $this->post('/muhasebe/entries/'.$id.'/tags',['tags'=>'Acil, Acil, Takip'])->assertSessionHasNoErrors();
 $this->get('/muhasebe?contact_id='.$directoryId.'&tag=Acil')->assertOk()->assertSee('Ada')->assertSee('data-contact=',false);
 $this->postJson('/muhasebe/entries/'.$id.'/tags',['tags'=>'Özel etiket'])->assertOk();
 $this->get('/muhasebe?contact_id='.$directoryId.'&tag='.urlencode('Özel etiket'))->assertOk()->assertSee('Özel etiket')->assertSee('Ada');
 $this->postJson('/muhasebe/entries/'.$id.'/tags',['tags'=>str_repeat('x',31)])->assertUnprocessable();
 $this->postJson('/muhasebe/entries/'.$id.'/tags',['tags'=>'Acil, Takip'])->assertOk();
 $this->assertSame(['Acil','Takip'],json_decode(DB::table('accounting_entries')->where('id',$id)->value('tags'),true));
 $this->post('/muhasebe/rehber/'.$directoryId,['name'=>'Ada','kind'=>'person','tags'=>'Güvenilir','return_to'=>'transactions'])->assertRedirect('/muhasebe#transactions');
 $this->get('/muhasebe?contact_id='.$directoryId.'&q=Ada')->assertOk()->assertSee('60,25')->assertSee('Güvenilir')->assertSee('Acil');
 $this->delete('/muhasebe/entries/'.$id)->assertSessionHasNoErrors();
 $this->get('/muhasebe')->assertOk()->assertDontSee('60,25');
 $this->assertDatabaseCount('accounting_payments',1);
 $this->get('/muhasebe?contact_id='.$directoryId.'&status=deleted')->assertOk()->assertSee('Ada');
 $this->post('/muhasebe/entries/'.$id.'/payments',['amount'=>'1','date'=>'2026-11-08','token'=>(string)Str::uuid()])->assertNotFound();
 $this->post('/muhasebe/entries/'.$id.'/restore')->assertSessionHasNoErrors();
 $this->get('/muhasebe?contact_id='.$directoryId.'&status=open')->assertOk()->assertSee('60,25');
 \Illuminate\Support\Facades\Storage::fake('local');
 $this->post('/muhasebe/profil',['name'=>'Test Firma','address'=>'İstanbul','tax_number'=>'1234567890','logo'=>\Illuminate\Http\UploadedFile::fake()->image('logo.png',200,80)])->assertSessionHasNoErrors();
 $this->get('/muhasebe/profil')->assertOk()->assertSee('Test Firma');
 $quoteProduct=DB::table('accounting_catalog')->insertGetId(['member_id'=>$member->id,'kind'=>'service','name'=>'Hizmet','normalized_name'=>'hizmet','unit'=>'saat','price'=>125000,'currency'=>'TRY','created_at'=>now(),'updated_at'=>now()]);
 $this->post('/muhasebe/quotes',['recipient_id'=>$directoryId,'currency'=>'TRY','valid_until'=>'','items'=>[['catalog_id'=>$quoteProduct,'quantity'=>2,'price'=>'12.50']]])->assertSessionHasNoErrors();
 $this->assertDatabaseHas('accounting_quotes',['total'=>250000,'valid_until'=>null]);
 $quoteId=DB::table('accounting_quotes')->value('id');
 $this->get('/muhasebe/teklifler/'.$quoteId)->assertOk()->assertSee('Test Firma')->assertSee('Ada')->assertSee('data:image/png;base64',false)->assertDontSee('Geçerlilik:');
 $this->post('/muhasebe/profil',['name'=>'Yeni Firma'])->assertSessionHasNoErrors();
 $this->get('/muhasebe/teklifler/'.$quoteId)->assertSee('Test Firma')->assertDontSee('Yeni Firma');
 $this->get('/muhasebe')->assertOk()->assertDontSee('TKL-');
 $this->get('/muhasebe/teklifler')->assertOk()->assertSee('Yeni teklif');
 $this->get('/muhasebe/teklifler?view=list')->assertOk()->assertSee('TKL-')->assertDontSee('id="items"',false);
 $this->get('/muhasebe/rehber')->assertOk()->assertSee('Ada')->assertSee('60,25')->assertSee('Alacak')->assertSee('Genel cari toplam');
 $this->getJson('/muhasebe/rehber?q=Ada')->assertOk()->assertJsonPath('total',1)->assertJsonStructure(['html','total']);
 $this->getJson('/muhasebe/rehber?q=bulunmayan')->assertOk()->assertJsonPath('total',0);
 $this->get('/muhasebe')->assertOk()->assertSee('Cari hesaplar')->assertDontSee('id="transactions"',false);
 $this->get('/muhasebe/rehber/ekle')->assertOk();
 $this->post('/muhasebe/directory',['kind'=>'product','name'=>'Yanlış'])->assertSessionHasErrors('kind');
 $this->post('/muhasebe/urunler',['kind'=>'service','name'=>'Bakım','unit'=>'saat','price'=>'250.50','currency'=>'TRY'])->assertRedirect('/muhasebe/urunler');
 $catalogId=DB::table('accounting_catalog')->where('name','Bakım')->value('id');
 $this->get('/muhasebe/urunler')->assertOk()->assertSee('Bakım');
 $this->get('/muhasebe/urunler/'.$catalogId.'/duzenle')->assertOk();
 $this->get('/muhasebe/rehber')->assertDontSee('Bakım');
 $this->post('/muhasebe/entries',['token'=>(string)Str::uuid(),'catalog_id'=>$catalogId,'type'=>'income','currency'=>'TRY','amount'=>'250.50','date'=>'2026-11-08'])->assertSessionHasErrors(['directory_id','catalog_id']);
 $this->assertDatabaseMissing('accounting_entries',['catalog_id'=>$catalogId]);
 $this->getJson('/muhasebe/directory?q=Ada')->assertOk()->assertJsonFragment(['name'=>'Ada']);
 $this->get('/muhasebe/rehber/'.$directoryId.'/duzenle')->assertOk();
 $this->post('/muhasebe/rehber/'.$directoryId,['name'=>'Ada','kind'=>'person','address'=>'Ankara','email'=>'ada@example.test','phone'=>'5551234567'])->assertRedirect('/muhasebe/rehber/'.$directoryId.'/duzenle');
 $this->get('/muhasebe/rehber/'.$directoryId.'/duzenle')->assertOk()->assertSee('Ankara')->assertSee('ada@example.test');
 $this->post('/muhasebe/rehber/'.$directoryId,['name'=>'Ada Yeni','kind'=>'company','address'=>'İzmir'])->assertSessionHasNoErrors();
 $this->assertDatabaseHas('accounting_directory',['id'=>$directoryId,'name'=>'Ada Yeni','normalized_name'=>'ada yeni','kind'=>'company']);
 $this->post('/muhasebe/rehber/'.$directoryId,['name'=>'Ada','kind'=>'person','address'=>'Ankara'])->assertSessionHasNoErrors();
 $this->assertDatabaseHas('accounting_directory',['id'=>$directoryId,'address'=>'Ankara']);
 $this->get('/muhasebe?directory_id='.$directoryId)->assertOk()->assertSee('✓ Seçildi: Ada');
 $this->get('/muhasebe?contact_id='.$directoryId)->assertOk()->assertSee('✓ Seçildi: Ada')->assertSee('data-auto-open="no"',false)->assertSee('value="open" selected',false);
 $this->get('/muhasebe?contact_id='.$directoryId.'&status=')->assertOk()->assertSee('value="" selected',false);
 $this->post('/muhasebe/directory',['kind'=>'company','name'=>'Atlas'])->assertRedirect('/muhasebe/rehber');
 $other=Member::create(['account_id'=>$account->id,'name'=>'Other','email'=>'other@example.test','password'=>'Password12345']);
 $this->actingAs($other,'enerjisa')->get('/muhasebe')->assertOk()->assertDontSee('Ada');
 $this->post('/muhasebe/entries/'.$id.'/tags',['tags'=>'Acil'])->assertNotFound();
 $this->postJson('/muhasebe/entries/'.$id.'/edit',['amount'=>'100','date'=>'2026-11-08'])->assertNotFound();
 $this->delete('/muhasebe/entries/'.$id)->assertNotFound();
 $this->post('/muhasebe/entries/'.$id.'/restore')->assertNotFound();
 $this->get('/muhasebe/teklifler/'.$quoteId)->assertNotFound();
 $this->getJson('/muhasebe/directory?kind=person&q=Ada')->assertJsonCount(0);
 $this->post('/muhasebe/entries',['token'=>(string)Str::uuid(),'directory_id'=>$directoryId,'type'=>'income','currency'=>'TRY','amount'=>'1','date'=>'2026-11-08'])->assertSessionHasErrors('directory_id');
 $this->post("/muhasebe/entries/$id/payments",['amount'=>'1','date'=>'2026-11-08','token'=>(string)Str::uuid()])->assertNotFound();
 }
}
